def by_category(cat):
    """تصاویر یک دسته به ترتیب تاریخ."""
    return [p for p in PHOTOS if p[0] == cat]


def counts():
    return {c: len(by_category(c)) for c in CATEGORIES}


def date_range(cat):
    items = by_category(cat)
    if not items:
        return ""
    return min(p[3] for p in items), max(p[3] for p in items)
